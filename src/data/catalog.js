export function getBook(id) {
  return books.find((item) => item.id === id) || null;
}

export function getPaper(id) {
  return papers.find((item) => item.id === id) || null;
}

export function searchBooks(query) {
  const q = query.trim().toLowerCase();
  if (!q) return books;
  return books.filter((item) =>
    [item.title, item.author, item.description, item.blurb, item.category, item.subjects.join(' '), String(item.year)]
      .join(' ')
      .toLowerCase()
      .includes(q),
  );
}
